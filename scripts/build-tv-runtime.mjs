// Deterministic, dependency-free classic JS builder for packaged Tizen 5.5.
// ES modules stay source-of-truth. VS Code Tizen Build Project does not run npm.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const inputs = [
  "app/src/navigation/remote.js",
  "app/src/navigation/focus.js",
  "app/src/navigation/premium-focus.js",
  "app/src/platform/capabilities.js",
  "app/src/platform/keys.js",
  "app/src/platform/startup-video.js",
  "app/src/views/view-state.js",
  "app/src/api/public-discovery.js",
  "app/src/platform/device-vault.js",
  "app/src/api/device-pairing.js",
  "app/src/api/channel-catalog.js",
  "app/src/api/recording-catalog.js",
  "app/src/main.js"
];
const output = join(root, "app/tv-runtime.js");
const presentationInputs = [
  "app/index.html", "app/styles.css", "app/config.xml", "package.json"
];

// Git for Windows can check out text as CRLF; TV runtime generation uses LF.
// Normalize BOTH the source files and the checked-out generated file.
function normalizeNewlines(text) { return text.replace(/\r\n?/g, "\n"); }

function makeRuntime() {
  const bodies = inputs.map(function (path) {
    const code = normalizeNewlines(readFileSync(join(root, path), "utf8"))
      // Tizen VS Code extension adds an editor-only index.d.ts reference.
      // It is not runtime code and must never enter the committed TV bundle.
      .replace(/^\/\/\/[ \t]*<reference[ \t]+path=["\']\.\.\/\.\.\/index\.d\.ts["\'][ \t]*\/>[ \t]*\n(?:[ \t]*\n)?/gm, "")
      .replace(/^import\s+\{[^}\n]+\}\s+from\s+["'][^"'\n]+["'];\r?\n/gm, "")
      .replace(/^export\s+(?=function\s)/gm, "");
    if (/^\s*(?:import|export)\s/m.test(code)) {
      throw new Error("Unsupported module syntax in " + path + "; update builder intentionally");
    }
    return "  // BEGIN " + path + "\n" +
      code.trimEnd().split("\n").map(line => "  " + line).join("\n") +
      "\n  // END " + path + "\n";
  }).join("\n");
  // The identity represents the packaged source, not a changing Git branch tip.
  const packageVersion = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version;
  const manifest = normalizeNewlines(readFileSync(join(root, "app/config.xml"), "utf8"));
  if (!manifest.includes('version="' + packageVersion + '"'))
    throw new Error("Tizen manifest and npm package versions differ");
  const digest = createHash("sha256").update(bodies);
  for (const path of presentationInputs) {
    digest.update(path + "\n");
    digest.update(normalizeNewlines(readFileSync(join(root, path), "utf8")));
  }
  const shortHash = digest.digest("hex").slice(0, 12);
  const label = "Samsung v" + packageVersion + " · S4.1 · b" + shortHash;
  const identity = "  const VDR_SUITE_BUILD_IDENTITY = Object.freeze(" +
    JSON.stringify({version: packageVersion, slice: "S4.1",
      build: shortHash, label: label}) + ");\n\n";
  return "/* Generated by npm run build:tv from app/src files. DO NOT EDIT.\n" +
    " * A classic single-file script supports packaged Tizen 5.5 file URLs.\n" +
    " */\n(function () {\n  \"use strict\";\n\n" + identity + bodies + "\n}());\n";
}

const expected = makeRuntime();
if (process.argv.includes("--check")) {
  let actual;
  try { actual = normalizeNewlines(readFileSync(output, "utf8")); }
  catch (_) { throw new Error("Missing app/tv-runtime.js: run npm run build:tv"); }
  if (actual !== expected) {
    throw new Error("Stale app/tv-runtime.js: run npm run build:tv and commit the result");
  }
  console.log("Tizen 5.5 classic runtime: synchronized");
} else {
  writeFileSync(output, expected, "utf8");
  console.log("Generated app/tv-runtime.js");
}
